// Runs every `*.attack.ts` case against a fresh harness, asserts the expected code and that nothing
// was authorized (controls must authorize), checks for duplicate charges, then prints the table and
// writes docs/EVAL.md.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { afterAll, describe, expect, it } from "vitest";
import { createHarness, type AttackCase } from "./harness.js";

const cases = Object.entries(import.meta.glob<{ default: AttackCase }>("./*.attack.ts", { eager: true }))
  .map(([file, m]) => ({ file: file.slice(2), c: m.default }))
  .sort((a, b) => a.c.id.localeCompare(b.c.id));

interface Row {
  c: AttackCase;
  code: string;
  authorized: boolean;
  duplicateCharges: number;
  total: number;
  pass: boolean;
}
const rows: Row[] = [];

describe("attack suite (SPEC §11)", () => {
  it("has at least 50 cases with unique ids", () => {
    expect(cases.length).toBeGreaterThanOrEqual(50);
    expect(new Set(cases.map((x) => x.c.id)).size).toBe(cases.length);
  });

  for (const { file, c } of cases) {
    it(`${c.id} ${c.title}`, async () => {
      const h = await createHarness(c.options);
      const out = await c.run(h);
      const dup = h.duplicateCharges();
      const wantAuth = c.expectAuthorized ?? false;
      const total = h.totalAuthorizations();
      const wantTotal = c.authorizations ?? (wantAuth ? 1 : 0);
      const reasonOk = !c.reason || (out.reason ?? "").includes(c.reason);
      const pass = out.code === c.expect && out.authorized === wantAuth && dup === 0 && total === wantTotal && reasonOk;
      rows.push({ c, code: out.code, authorized: out.authorized, duplicateCharges: dup, total, pass });
      const reason = reasonOk ? "ok" : (out.reason ?? "none");
      expect({ file, code: out.code, authorized: out.authorized, dup, total, reason }).toEqual({
        file,
        code: c.expect,
        authorized: wantAuth,
        dup: 0,
        total: wantTotal,
        reason: "ok",
      });
    });
  }
});

afterAll(() => {
  if (rows.length === 0) return;
  rows.sort((a, b) => a.c.id.localeCompare(b.c.id));
  const attacks = rows.filter((r) => r.c.category !== "control");
  // Any authorization beyond what the case declares counts, setup submits included.
  const unauthorized = attacks.filter(
    (r) => (r.authorized && !r.c.expectAuthorized) || r.total > (r.c.authorizations ?? (r.c.expectAuthorized ? 1 : 0)),
  ).length;
  const dupes = rows.reduce((n, r) => n + r.duplicateCharges, 0);
  const passed = rows.filter((r) => r.pass).length;

  const w = { id: 4, cat: 11, exp: 20, got: 20 };
  const pad = (s: string, n: number) => s.padEnd(n).slice(0, n);
  const lines = [
    `${pad("id", w.id)}  ${pad("category", w.cat)}  ${pad("expected", w.exp)}  ${pad("got", w.got)}  auth  ok  title`,
    ...rows.map(
      (r) =>
        `${pad(r.c.id, w.id)}  ${pad(r.c.category, w.cat)}  ${pad(r.c.expect, w.exp)}  ${pad(r.code, w.got)}  ${r.authorized ? "yes " : "no  "}  ${r.pass ? "✓ " : "✗ "}  ${r.c.title}`,
    ),
    "",
    `${passed}/${rows.length} passed · ${attacks.length} attacks · unauthorized authorizations: ${unauthorized} · duplicate charges: ${dupes}`,
  ];
  process.stdout.write(`\n${lines.join("\n")}\n`);

  // EVAL.md is only rewritten by a full run, so a filtered run can't shrink it.
  if (rows.length !== cases.length) return;
  const specItems = [...new Set(rows.map((r) => r.c.spec))];
  const md = [
    "# Handshake attack eval",
    "",
    'Generated by `pnpm attack` (tests/attacks/eval.test.ts). Do not edit by hand, except the "Live sandbox evidence" section at the end, which is kept as written.',
    "",
    "Each case starts from a fully valid signed request (real merchant gate, in-memory stores, fake PayPal,",
    "fake WebAuthn authenticator) and changes one thing. A case passes when the gate returns the expected",
    "code, nothing new is authorized at PayPal (controls must authorize), and no request id is created",
    "twice nor any authorization captured twice. Every case also checks the total number of authorizations",
    "it leaves (setup included), so an attack can't authorize in a step the case doesn't report. Duplicate",
    "charges count a second authorized order for one offer, a second PayPal authorize for one order, and a",
    "second capture of one authorization. Where several checks share a code, the case also checks the",
    "gate's recorded reason.",
    "",
    "Limits: the stores are in memory, so the concurrency cases (parallel split orders, parallel duplicate",
    "requests) show the gate's logic, not Postgres isolation; that is covered against Neon by",
    "`services/merchant/test/gate-store.db.test.ts`. The currency cases stop at the schema (USD only), so",
    "the step-5 currency comparison is defence in depth that this suite doesn't reach.",
    "",
    "| | Count |",
    "|---|---|",
    `| Cases | ${rows.length} (${rows.length - attacks.length} controls, ${attacks.length} attacks) |`,
    `| Passed | ${passed} |`,
    `| SPEC §11 items covered | ${specItems.filter((s) => s !== "control").length} |`,
    `| Unauthorized authorizations | ${unauthorized} |`,
    `| Duplicate charges | ${dupes} |`,
    "",
    "| ID | SPEC §11 item | Attack | Expected | Result | Authorized | Pass |",
    "|---|---|---|---|---|---|---|",
    ...rows.map(
      (r) =>
        `| ${r.c.id} | ${r.c.spec} | ${r.c.title} | \`${r.c.expect}\` | \`${r.code}\` | ${r.authorized ? "yes" : "no"} | ${r.pass ? "✅" : "❌"} |`,
    ),
    "",
  ].join("\n");
  // The hand-written live sandbox section (from `## Live sandbox evidence` on) survives regeneration.
  const file = new URL("../../docs/EVAL.md", import.meta.url);
  const old = existsSync(file) ? readFileSync(file, "utf8") : "";
  const at = old.indexOf("\n## Live sandbox evidence");
  writeFileSync(file, at >= 0 ? `${md}${old.slice(at + 1)}` : md);
});
